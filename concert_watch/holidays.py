COVERED_YEARS = (2026, 2027)


def name(d: date | str) -> str:
    """공휴일이면 이름, 아니면 빈 문자열."""
    key = d if isinstance(d, str) else d.isoformat()
    return HOLIDAYS.get(key, "")


def is_holiday(d: date | str) -> bool:
    return bool(name(d))


def is_covered(d: date) -> bool:
    """이 날짜의 연도를 표에 갖고 있는지. 없으면 '공휴일 아님'이 아니라 '모름'이다."""
    return d.year in COVERED_YEARS
